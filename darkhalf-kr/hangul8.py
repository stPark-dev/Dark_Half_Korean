# 세로모음: (세로줄 x 목록, 가지 x, 가지 개수)
# ㅐㅔ 처럼 ㅣ 가 붙는 것은 두 세로줄을 5·7 로 띄운다. 6·7 로 붙이면 2픽셀
# 굵은 줄 하나로 보여 「세」가 「서」로 읽힌다.
VTAB = {
 'ㅏ': ([5],   6, 1), 'ㅑ': ([5],   6, 2),
 'ㅐ': ([5,7], 6, 1), 'ㅒ': ([5,7], 6, 2),
 'ㅓ': ([6],   5, 1), 'ㅕ': ([6],   5, 2),
 'ㅔ': ([5,7], 4, 1), 'ㅖ': ([5,7], 4, 2),
 'ㅣ': ([6],   None, 0),
}


def _vow(ch, y0, y1, jong):
    """중성 픽셀 (x,y) 목록. y0..y1 은 쓸 수 있는 세로 범위."""
    p = []
    if ch in VOW_V:
        stems, bx, nb = VTAB[ch]
        for x in stems:
            for y in range(y0, y1+1): p.append((x, y))
        mid = (y0 + y1) // 2
        for yy in ([mid] if nb == 1 else [mid-1, mid+1] if nb == 2 else []):
            if y0 <= yy <= y1: p.append((bx, yy))
        return p
    if ch in VOW_H:
        # ㅗㅛ 는 줄이 아래, ㅜㅠ 는 위. ㅡ 는 가운데보다 조금 아래에 둔다 —
        # y0 에 두면 초성 바로 밑에 붙어 「의」가 ㅇ 에 줄 하나 그은 꼴이 된다.
        bar = y1 if ch in "ㅗㅛ" else (y0 if ch != 'ㅡ' else max(y0, y1 - 1))
        for x in range(0, 8): p.append((x, bar))
        if ch == 'ㅡ': return p
        stems = [3] if ch in "ㅗㅜ" else [2, 5]
        for x in stems:
            for y in ((range(y0, bar)) if ch in "ㅗㅛ" else range(bar+1, y1+1)):
                p.append((x, y))
        return p
    # 섞임 — 가로 부분 + 오른쪽 세로줄
    base = {'ㅘ':'ㅗ','ㅙ':'ㅗ','ㅚ':'ㅗ','ㅝ':'ㅜ','ㅞ':'ㅜ','ㅟ':'ㅜ','ㅢ':'ㅡ'}[ch]
    p = [(x, y) for (x, y) in _vow(base, y0, y1, jong) if x < 6]
    for y in range(y0, y1+1): p.append((7, y))
    return p


def glyph(ch):
    """8x8 불리언 격자 (행 우선). 한글 음절만."""
    g = [[False]*8 for _ in range(8)]
    o = ord(ch) - 0xAC00
    if not (0 <= o < 11172): return g
    cho, jung, jong = CHO[o//588], JUNG[(o%588)//28], JONG[o%28]
    def blit(art, x0, y0):
        for dy, row in enumerate(art):
            for dx, c in enumerate(row):
                if c == '#' and 0 <= x0+dx < 8 and 0 <= y0+dy < 8:
                    g[y0+dy][x0+dx] = True
    if jung in VOW_V:
        if jong == ' ':
            blit(CV[cho], 0, 1); vy = (0, 7)
        else:
            blit(CV[cho], 0, 0); vy = (0, 4)
        for x, y in _vow(jung, vy[0], vy[1], jong != ' '):
            if 0 <= x < 8 and 0 <= y < 8: g[y][x] = True
    else:
        if jong == ' ':
            blit(CH4.get(cho, CH[cho]), 1, 0); vy = (4, 7)
        else:
            blit(CH[cho], 1, 0); vy = (3, 4)
        for x, y in _vow(jung, vy[0], vy[1], jong != ' '):
            if 0 <= x < 8 and 0 <= y < 8: g[y][x] = True
    if jong != ' ':
        blit(JG.get(jong, JG['ㅇ']), 1, 5)
    return g
