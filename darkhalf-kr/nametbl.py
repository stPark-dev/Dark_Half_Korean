#!/usr/bin/env python3
"""이름표 — 포인터 표 + 0xFF 종료 문자열 구조를 쓰는 표들.

words.py 의 단어표와 같은 형식이다. 포인터는 뱅크 내 오프셋 그 자체이고
(0x8000 을 씌우거나 벗기지 않는다) 문자열은 0xFF 로 끝난다.
길이를 바꿔도 되지만 구간 상한을 넘지 않아야 한다.

## 왜 이 표들을 번역해야 하는가

가나 글리프 슬롯을 한글에 내주는 설계이므로, 번역하지 않은 문자열은
한글 잡음으로 렌더된다. 마법 이름이 「말들해만되士당입」 으로 나오면
어떤 화면도 판독할 수 없다.

## 왜 옮기면 안 되는가 (제자리 고정)

마법 문자열을 가리키는 표가 하나가 아니다.
  0x040300  포인터 표 (2바이트 간격)
  0x04f139  레코드 표 (4바이트 간격, 이름 포인터 + 다른 포인터)
  0x05b517  설명문 본문이 「F0 C4 <포인터>」 로 이름 주소를 직접 박아 쓴다

처음에는 문자열을 재배치하고 0x040300 만 고쳤다. 나머지 둘이 어긋나
메뉴에서 게임이 멈췄다. 그래서 각 엔트리는 원본 시작 주소를 지키고
포인터 표는 건드리지 않는다.

## 이름 창도 2바이트 이스케이프를 정상 처리한다 (확인됨)

한때 이름 창이 이스케이프를 못 읽는다고 의심했다. 아이템 창에 「힐」 이
「보힐」 로 나왔기 때문이다 (실기 확인). 틀린 추측이었다.

실제 원인은 0xA0(♥) 이었다. 이름 앞에 붙는 커서 표시인데 회수 대상에
들어가 「보」 가 배정됐다. 「보힐」 = ♥ + 힐 이고, 「힐」(f6 8a) 자체는
이스케이프가 옳게 처리된 결과였다. krcodec.KEEP 에 0xA0 을 넣어 고쳤다.

그래서 이름표는 2바이트 코드를 자유롭게 쓸 수 있다. 단일바이트를 강제할
필요가 없다 — 강제하면 대사 43개가 예산을 넘긴다.

## 마법 이름 (구조 확정)

  포인터 표  0x040300  18엔트리 x 2바이트
  문자열     0x04f3d3 ~ 0x04f45b  (137바이트)
  구간 상한  0x04f45c  — 그 뒤는 コンディション / フォーメーション 라벨이다

[0x11] 은 문자열이 아니라 <EB><17> 로 단어표 엔트리 [0x17] 을 참조한다
(ダークゲート -> 마계문). 단어표에서 번역했으므로 그대로 둔다.

## 아이템·장비 표 — 해결 (PROGRESS 4.37)

  포인터 표  0x040260  120엔트리
  문자열     0x04f137 ~ 0x04f470   (뱅크 0x04)

이 구간은 TSV 가 정본이다 (build.LIST_TBL). 조립 언어로 쓰여 있다.

  EE lo hi      ptr 로 **꼬리 점프**한다. 이 엔트리는 여기서 끝난다
  F0 C4 lo hi   ptr 의 문자열을 끼워 넣고 계속 읽는다 (「＋１」 변형)
  EB N          단어표 N 번을 끼워 넣는다
  0xFF          끝

**<EE> 를 지우면 안 된다.** 열한 엔트리는 0xFF 종료자가 아예 없고 <EE> 가
끝을 표시한다 (0x04f1de 등). 리터럴로 풀어 썼더니 남는 칸을 지나 다음
엔트리의 F0 C4 를 읽고 자기 자신을 다시 참조했다.

접미어는 공유한다. 오프셋이 0 이 아닌 참조는 셋이고, 접미어를 짧게 바꿀 때
**포인터를 새 위치로 옮겼다** (그 두 바이트는 우리가 다시 쓰는 엔트리 안에
있으므로 옮겨도 된다).

  0x04f1c4 「ソード」  -> 0x04f1c1 「검」    ([00] 「소검」 의 둘째 바이트)
  0x04f2d6 「アーマー」 -> 0x04f2d4 「갑주」  ([28] 「강철갑주」 의 셋째 바이트)
  0x04f37a 「シールド」 -> 0x04f378 「실드」  ([44] 「하드실드」 의 셋째 바이트)

목록 창은 조립 결과 바이트 하나를 타일 하나로 그린다. 그래서 이 구간의
음절은 전부 단일바이트여야 하고, 창 장식 칸(krcodec.hw_ui)에 앉아서도
안 된다. 역검증 [16]·[17] 이 조립기를 흉내 내어 확인한다.

## 아직 풀지 못한 표

  몬스터       포인터 표 0x04f587. 구분자가 0xFF 가 아니고 엔트리가 서로
               겹쳐 읽힌다. 아이템 표와 같은 접미사 공유일 가능성이 크다
               (「オーク」 「オークキング」 「オークロード」 가 이어져 있다).
  인물 이름    미발견. 0x0405be 는 종반 대사 포인터 표였다.
"""

# (이름, 포인터표, 뱅크 베이스, 엔트리 수, 문자열 시작, 구간 상한)
SPELL = dict(name="마법 이름", ptr=0x040300, bank=0x040000, count=18,
             data=0x04f3d3, limit=0x04f45c)

# 원문과 한국어. None 이면 원본 바이트를 그대로 둔다.
SPELL_WORDS = [
    ("ファイアボール",   "불길"),
    ("アイスストーム",   "서리"),
    ("ライトニング",   "번개"),
    ("ウインドブレード",   "바람"),
    ("マジックアロー",   "마법살"),
    ("デス",   "죽음"),
    ("ヒール",   "치유"),
    ("キュア",   "해독"),
    ("ディスペル",   "해제"),
    ("シールド",   "방어"),
    ("カウンターマジック",   "반사"),
    ("コンフュージョン",   "광기"),   # 혼(25)·란(30) 두 칸을 광(2) 한 칸으로
    ("パラライズ",   "마비"),
    ("ポイズンブロウ",   "독무"),
    ("スリープ",   "수면"),
    ("ストレングス",   "강신"),
    ("アンデッド",   "파사"),
    ("<EB><17>",         None),      # 단어표 참조(다크게이트). 그대로 둔다
]
assert len(SPELL_WORDS) == SPELL["count"]

TABLES = [(SPELL, SPELL_WORDS)]


def slots(rom, spec):
    """원본 엔트리의 (시작주소, 쓸 수 있는 바이트). 마지막 1바이트는 종료자."""
    st, i = [], spec["data"]
    for _ in range(spec["count"]):
        st.append(i); j = i
        while rom[j] != 0xFF: j += 1
        i = j + 1
    st.append(i)
    return [(st[k], st[k+1] - st[k] - 1) for k in range(spec["count"])]


def pairs(rom):
    """(용량, 한국어) — 예산 우선 배정용."""
    out = []
    for spec, wl in TABLES:
        for (a, cap), (_, kr) in zip(slots(rom, spec), wl):
            if kr: out.append((cap, kr))
    return out


def texts():
    """음절 배정에 넣어야 하는 한국어."""
    return [kr for _, w in TABLES for _, kr in w if kr]




if __name__ == "__main__":
    for spec, wl in TABLES:
        print(f"=== {spec['name']}  {spec['count']}엔트리 ===")
        for i, (ja, kr) in enumerate(wl):
            print(f" [{i:02X}] {ja:<18} -> {kr if kr else '(원문 유지)'}")
        print(f"번역 대상 {sum(1 for _, k in wl if k)}개\n")
