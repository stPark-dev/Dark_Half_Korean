#!/usr/bin/env python3
"""이름표 — 포인터 표 + 0xFF 종료 문자열 구조를 쓰는 표들.

words.py 의 단어표와 같은 형식이다. 포인터는 뱅크 내 오프셋 그 자체이고
(0x8000 을 씌우거나 벗기지 않는다) 문자열은 0xFF 로 끝난다.
길이를 바꿔도 되지만 구간 상한을 넘지 않아야 한다.

## 왜 이 표들을 번역해야 하는가

가나 글리프 슬롯을 한글에 내주는 설계이므로, 번역하지 않은 문자열은
한글 잡음으로 렌더된다. 마법 이름이 「말들해만되士당입」 으로 나오면
어떤 화면도 판독할 수 없다.

## 마법 이름 (구조 확정)

  포인터 표  0x040300  18엔트리 x 2바이트
  문자열     0x04f3d3 ~ 0x04f45b  (137바이트)
  구간 상한  0x04f45c  — 그 뒤는 コンディション / フォーメーション 라벨이다

[0x11] 은 문자열이 아니라 <EB><17> 로, 단어표 엔트리 [0x16](ダークゲート
-> 다크게이트)을 참조한다. 단어표에서 이미 번역했으므로 그대로 둔다.

## 아직 풀지 못한 표

  아이템·장비  포인터 표 0x040260. 「<F0>と<FA><F1>十１」 형태의 +1/+2/+3
               변형이 섞여 있어 기본 이름과 변형 틀을 갈라야 한다.
  몬스터       포인터 표 0x04f587. 구분자가 0xFF 가 아니다. 엔트리가
               서로 겹쳐 읽히므로 구분자를 먼저 알아내야 한다.
  인물 이름    미발견. 0x0405be 는 종반 대사 포인터 표였다.
"""

# (이름, 포인터표, 뱅크 베이스, 엔트리 수, 문자열 시작, 구간 상한)
SPELL = dict(name="마법 이름", ptr=0x040300, bank=0x040000, count=18,
             data=0x04f3d3, limit=0x04f45c)

# 원문과 한국어. None 이면 원본 바이트를 그대로 둔다.
SPELL_WORDS = [
    ("ファイアボール",   "파이어볼"),
    ("アイスストーム",   "아이스스톰"),
    ("ライトニング",     "라이트닝"),
    ("ウインドブレード", "윈드블레이드"),
    ("マジックアロー",   "매직애로"),
    ("デス",             "데스"),
    ("ヒール",           "힐"),
    ("キュア",           "큐어"),
    ("ディスペル",       "디스펠"),
    ("シールド",         "실드"),
    ("カウンターマジック", "카운터매직"),
    ("コンフュージョン", "컨퓨전"),
    ("パラライズ",       "패럴라이즈"),
    ("ポイズンブロウ",   "포이즌블로"),
    ("スリープ",         "슬립"),
    ("ストレングス",     "스트렝스"),
    ("アンデッド",       "언데드"),
    ("<EB><17>",         None),      # 단어표 참조(다크게이트). 그대로 둔다
]
assert len(SPELL_WORDS) == SPELL["count"]

TABLES = [(SPELL, SPELL_WORDS)]


def texts():
    """음절 배정에 넣어야 하는 한국어."""
    return [kr for _, w in TABLES for _, kr in w if kr]


if __name__ == "__main__":
    for spec, wl in TABLES:
        print(f"=== {spec['name']}  {spec['count']}엔트리 ===")
        for i, (ja, kr) in enumerate(wl):
            print(f" [{i:02X}] {ja:<18} -> {kr if kr else '(원문 유지)'}")
        print(f"번역 대상 {sum(1 for _, k in wl if k)}개\n")
