def slots(rom):
    """원본 엔트리의 (시작주소, 쓸 수 있는 바이트) 목록.

    제자리 방식이라 각 엔트리는 원본 시작 주소를 지킨다. 마지막 1바이트는
    0xFF 종료자 몫이다. 옮기면 안 되는 이유는 모듈 주석의 '왜 옮기면
    안 되는가' 를 볼 것.
    """
    st, i = [], DATA
    for _ in range(COUNT):
        st.append(i); j = i
        while rom[j] != 0xFF: j += 1
        i = j + 1
    st.append(i)
    return [(st[k], st[k+1] - st[k] - 1) for k in range(COUNT)]


def pairs(rom):
    """(용량, 한국어) — 예산 우선 배정을 받게 하려면 이 형태로 넘긴다."""
    return [(cap, kr) for (a, cap), (_, kr) in zip(slots(rom), WORDS) if kr]


def texts():
    """음절 배정에 넣어야 하는 한국어 문자열들."""
    return [kr for _, kr in WORDS if kr]


def tag(n):
    """엔트리 인덱스 -> 본문에 쓰는 표기. <EB> 다음 바이트는 인덱스+1 이다."""
    return f"<EB><{n+1:02X}>"


